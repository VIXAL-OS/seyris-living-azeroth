"""Freezes Fields.cpp's own UpdateShore as an independent reference for the shore worker's tests.

Writes tests/shore/reference_shore.hpp from src/env/Fields.cpp: the function itself, its model
constants and its Smooth/Clamp01 helpers, copied verbatim. The only edits: the scratch vectors are
not static, and the index lambda captures the fixture (its grid size is a member, so tests can use
small grids). With --check, exits 1 if the committed header no longer matches Fields.cpp (UpdateShore
changed: re-run without --check, and re-check env/ShoreField.cpp against it).
"""
from pathlib import Path
import hashlib
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "env" / "Fields.cpp"
TARGET = Path(__file__).resolve().parent / "reference_shore.hpp"


def block(text: str, start: int) -> str:
    """The text from `start` through the brace that closes the first block opened after it."""
    open_at = text.index("{", start)
    depth = 0
    for k in range(open_at, len(text)):
        if text[k] == "{":
            depth += 1
        elif text[k] == "}":
            depth -= 1
            if depth == 0:
                return text[start:k + 1]
    raise ValueError("unbalanced braces")


def line_of(text: str, pattern: str) -> str:
    match = re.search(r"^[ \t]*" + pattern + r".*$", text, re.M)
    if not match:
        raise ValueError(f"not found in Fields.cpp: {pattern}")
    return match.group(0).strip()


def generate() -> str:
    text = SOURCE.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    update = block(text, text.index("        void UpdateShore()"))
    smooth = block(text, text.index("        float Smooth("))
    clamp = line_of(text, r"float Clamp01\(")
    constants = [line_of(text, r"constexpr float " + name) for name in
                 ("kCell ", "kShoreNear ", "kShoreLow ", "kHeatNear ", "kHotGroundShare ")]
    if update.count("static std::vector") != 2 or update.count("auto at = [](int a, int b)") != 1:
        raise ValueError("UpdateShore's shape changed: review the extraction edits")
    digest = hashlib.sha256(update.encode("utf-8")).hexdigest()
    body = update.replace("static std::vector", "std::vector").replace("auto at = [](int a, int b)", "auto at = [this](int a, int b)")
    out = [
        "// GENERATED by make_reference.py from src/env/Fields.cpp -- do not edit.",
        f"// UpdateShore sha256 (as in Fields.cpp): {digest}",
        "// Verbatim except: scratch vectors not static; the index lambda captures the fixture (kSize is a member).",
        "#pragma once",
        "#include <cstdint>",
        "#include <vector>",
        "namespace reference",
        "{",
        "    namespace grassperf { inline double Now() { return 0.0; } }",
        "    // The fields UpdateShore reads and writes, as in Fields.cpp's Cell; `valid` stands for Live().",
        "    struct Cell",
        "    {",
        "        bool valid = false;",
        "        float z = 0.0f;",
        "        bool submerged = false; float waterZ = 0.0f; uint32_t liquid = 0;",
        "        float liquidMoisture = 1.0f, liquidTemp = 0.0f; bool liquidHot = false;",
        "        uint32_t nearLiquid = 0; float nearMoisture = 0.0f, nearTemp = 0.0f, heat = 0.0f; bool nearHot = false;",
        "        float hotShare = 0.0f, hotTemp = 0.0f;",
        "        float groundHeat = 0.0f, groundHeatTemp = 0.0f, groundHeatDist = -1.0f;",
        "        float shore = 0.0f, waterDist = -1.0f, aboveWater = 0.0f;",
        "    };",
        "    struct Fixture",
        "    {",
        "        int kSize = 0;",
        "        std::vector<Cell> cells;",
        "        struct { unsigned water = 0, hotGround = 0; double transformMs = 0.0; } g_stats;",
    ]
    out += ["        static " + c for c in constants]
    out += [
        "        Cell* Live(int a, int b) { Cell& c = cells[static_cast<size_t>(b) * kSize + a]; return c.valid ? &c : nullptr; }",
        "        static " + clamp,
        "        static " + smooth.strip(),
        body.rstrip(),
        "    };",
        "}",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    generated = generate()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current != generated:
            print("reference_shore.hpp is out of date with src/env/Fields.cpp (UpdateShore changed?)")
            return 1
        print("reference_shore.hpp matches src/env/Fields.cpp UpdateShore")
        return 0
    TARGET.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
