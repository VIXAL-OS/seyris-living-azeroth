"""Bakes the outlines of the 3.3.5a client's footprint textures into src/features/FootprintOutlines.hpp.

The rims of sand around footprints (features/CoverRipples.hpp) follow the print's own outline. The client draws a
print with one of six 32 x 32 textures (FootprintTextures.dbc: textures\\Footsteps\\*Footprint.blp), mostly alpha. Per
texture this measures the outline once: the alpha, lightly blurred (so a paw's toes and pad close into one shape),
cut at a quarter of its peak; its centroid; and how far the shape reaches from there along kRays directions in the
texture (u right, v down, as the client samples it). CoverRipples maps that onto the ground with each print's own
texture coordinates.

Run: python gen_footprint_outlines.py <folder with the .blp files and FootprintTextures.dbc> <output .hpp>
(the files as waterscan --extract/--extract-list writes them: textures#Footsteps#BaseFootprint.blp, ...).
"""
import math
import os
import struct
import sys

from PIL import Image, ImageFilter

RAYS = 64
SCALE = 4          # measured on the texture upsampled 4 x
BLUR_TEXELS = 1.5  # Gaussian blur, in the texture's texels
THRESHOLD = 0.25   # of the blurred alpha's peak


def read_dbc(path):
    d = open(path, 'rb').read()
    magic, n, fields, size, _ = struct.unpack_from('<4sIIII', d, 0)
    assert magic == b'WDBC' and fields == 2 and size == 8, (magic, fields, size)
    strings = 20 + n * size
    rows = []
    for i in range(n):
        ident, off = struct.unpack_from('<II', d, 20 + i * size)
        name = d[strings + off: d.index(b'\0', strings + off)].decode()
        rows.append((ident, name))
    return rows


def outline(path):
    im = Image.open(path).convert('RGBA')
    a = im.getchannel('A')
    w, h = a.size
    big = a.resize((w * SCALE, h * SCALE), Image.BILINEAR).filter(ImageFilter.GaussianBlur(BLUR_TEXELS * SCALE))
    bw, bh = big.size
    px = big.load()
    peak = max(px[x, y] for x in range(bw) for y in range(bh))
    cut = THRESHOLD * peak
    sx = sy = s = 0.0
    for y in range(bh):
        for x in range(bw):
            if px[x, y] >= cut:
                sx += x + 0.5
                sy += y + 0.5
                s += 1
    cx, cy = sx / s, sy / s
    radii = []
    for i in range(RAYS):
        ph = 2.0 * math.pi * i / RAYS
        dx, dy = math.cos(ph), math.sin(ph)
        far, r = 0.0, 0.0
        while True:
            x, y = cx + dx * r, cy + dy * r
            if not (0 <= x < bw and 0 <= y < bh):
                break
            if px[int(x), int(y)] >= cut:
                far = r
            r += 0.25
        radii.append(far / bw)
    return cx / bw, cy / bh, radii


def main():
    folder, out = sys.argv[1], sys.argv[2]
    rows = read_dbc(os.path.join(folder, 'FootprintTextures.dbc'))
    lines = []
    for ident, name in rows:
        flat = name.replace('\\', '#')
        path = os.path.join(folder, flat + '.blp')
        if not os.path.exists(path):
            path = os.path.join(folder, flat.replace('textures#', 'TEXTURES#') + '.blp')
        cu, cv, radii = outline(path)
        short = name.split('\\')[-1]
        values = ', '.join('%.4ff' % r for r in radii)
        lines.append('        { %d, "%s", %.4ff, %.4ff, { %s } },' % (ident, short, cu, cv, values))
    header = '''// Generated by tools/gen_footprint_outlines.py from the 3.3.5a client's footprint textures (FootprintTextures.dbc,
// textures\\Footsteps\\*Footprint.blp, 32 x 32). Don't edit by hand: run the tool again.
//
// Per texture: the centroid of its shape (alpha blurred by %.1f texels, cut at %d%% of its peak) in the texture's
// coordinates (u right, v down, 0..1), and how far the shape reaches from there along kOutlineRays directions
// (angle 2 pi i / kOutlineRays from +u toward +v), in the same units.
#pragma once

namespace wxl_livingazeroth::cover::ripples
{
    constexpr int kOutlineRays = %d;

    struct BakedOutline
    {
        int texture;        // FootprintTextures.dbc ID, as the client keeps it with each print
        const char* name;
        float cu, cv;
        float radius[kOutlineRays];
    };

    constexpr BakedOutline kOutlines[] = {
%s
    };

    inline const BakedOutline* FindOutline(int texture)
    {
        for (const BakedOutline& o : kOutlines)
            if (o.texture == texture) return &o;
        return nullptr;
    }
}
''' % (BLUR_TEXELS, int(THRESHOLD * 100), RAYS, '\n'.join(lines))
    with open(out, 'w', newline='\n') as f:
        f.write(header)
    print('wrote %d outlines to %s' % (len(rows), out))


if __name__ == '__main__':
    main()
